function detectLocale() {
  // Follow the OS/browser language; default to zh when unknown (e.g. Node tests
  // have no navigator, and existing tests assert Chinese output).
  const lang = (typeof navigator !== 'undefined' && (navigator.language || navigator.userLanguage) || '').toLowerCase();
  if (!lang) return 'zh';
  return lang.startsWith('en') ? 'en' : 'zh';
}

let locale = detectLocale();

function t(key, params) {
  const table = MESSAGES[locale] || MESSAGES.zh;
  let s = key in table ? table[key] : (key in MESSAGES.zh ? MESSAGES.zh[key] : key);
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : ''));
  return s;
}

function getLocale() { return locale; }
function setLocale(l) { if (l === 'zh' || l === 'en') locale = l; }

// Manual language override, persisted per-device. Stored value is one of
// 'system' | 'zh' | 'en'; 'system' (or anything unset/invalid) means "follow
// the OS/browser language" via detectLocale().
const LANGUAGE_STORAGE_KEY = 'tmux-desk-language';

function loadStoredLanguage() {
  try {
    const value = typeof localStorage !== 'undefined' ? localStorage.getItem(LANGUAGE_STORAGE_KEY) : null;
    return value === 'zh' || value === 'en' ? value : 'system';
  } catch { return 'system'; }
}

function saveLanguage(value) {
  const normalized = value === 'zh' || value === 'en' ? value : 'system';
  try { if (typeof localStorage !== 'undefined') localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized); } catch { /* ignore */ }
  return normalized;
}

function resolveLocale(stored = loadStoredLanguage()) {
  return stored === 'zh' || stored === 'en' ? stored : detectLocale();
}

// Apply translations to static markup via data-i18n* attributes.
function applyStaticI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
}

module.exports = {
  t, getLocale, setLocale, applyStaticI18n, detectLocale, MESSAGES,
  loadStoredLanguage, saveLanguage, resolveLocale,
};
